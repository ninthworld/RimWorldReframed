using System;
using ReframedUI;

int checks = 0;
void Check(bool value, string message) { if (!value) throw new Exception(message); checks++; }
var history = new PawnNeedsNovelty();
history.Observe(new[] { 1, 2 });
Check(!history.IsNew(1) && !history.IsNew(2), "Initial populated baseline is not novelty");
history.Observe(new[] { 1, 2, 3 });
Check(history.IsNew(3), "New group after baseline has novelty");
history.Shown(3, 1000, 10);
history.Shown(3, 1000, 11);
history.Shown(3, 1000, 12);
Check(history.IsNew(3), "Paused rendered frames consume no game time");
history.Shown(3, 1100, 13);
history.Shown(3, 1100, 13);
Check(history.IsNew(3), "Repeated events do not double-count shown time");
history.StopShowing();
history.Shown(3, 9000, 500);
Check(history.IsNew(3), "Switching away and back preserves novelty without charging unseen time");
history.Shown(3, 9100, 501);
history.Shown(3, 10000, 900);
Check(history.IsNew(3), "Frame gap from another tab does not consume shown time");
history.Shown(3, 10216, 901);
Check(history.IsNew(3), "Dot remains until exactly417 accumulated shown game ticks");
history.Shown(3, 10217, 902);
Check(!history.IsNew(3), "Dot expires at417 shown game ticks");
history.Observe(new[] { 1, 2 });
Check(!history.IsNew(3), "Absent groups do not retain visible markers");
history.Observe(new[] { 1, 2, 3 });
Check(history.IsNew(3), "Observed disappearance/reappearance is a newly appeared group");
history.Shown(3, 500, 1000);
history.Shown(3, 300, 1001);
Check(history.IsNew(3), "Tick rollback cannot consume novelty time");
var emptyBaseline = new PawnNeedsNovelty();
emptyBaseline.Observe(Array.Empty<int>());
emptyBaseline.Observe(new[] { 4 });
Check(emptyBaseline.IsNew(4), "A later thought after an empty baseline is new");
var otherPawn = new PawnNeedsNovelty();
otherPawn.Observe(new[] { 3 });
Check(!otherPawn.IsNew(3), "Different pawn has an independent initial baseline");
history.StopShowing();
Check(history.IsNew(3), "Scroll reset does not erase pawn novelty history");
Check(PawnNeedsGeometry.FullyVisible(21, 42, 20, 30), "Complete row gets shown-time credit");
Check(!PawnNeedsGeometry.FullyVisible(21, 42, 22, 30), "Top-clipped row gets no shown-time credit");
Check(!PawnNeedsGeometry.FullyVisible(21, 42, 20, 21), "Bottom-clipped row gets no shown-time credit");
Check(PawnNeedsGeometry.PolarityDivider(0, -1) && PawnNeedsGeometry.PolarityDivider(1, -1), "One separator at nonnegative-to-negative boundary");
Check(!PawnNeedsGeometry.PolarityDivider(-2, -3), "No separators between negative rows");
Check(PawnNeedsGeometry.ListHeight(6, true, PawnNeedsGeometry.NeedRow) == 160, "All six actual needs fit in160 logical pixels");
Check(PawnNeedsGeometry.ListHeight(9, true, PawnNeedsGeometry.ThoughtRow) == 190, "Nine thought rows plus polarity divider fit195-pixel thought viewport");
Console.WriteLine($"PASS {checks} Needs novelty/visible-time/overflow geometry contracts; no live acceptance claimed.");
